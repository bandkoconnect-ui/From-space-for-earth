import asyncio, sys
sys.path.insert(0, ".")
from phone_helpers import *
from playwright.async_api import async_playwright

async def main():
    srv, port = serve("mobile")
    log, problems = [], []
    async with async_playwright() as p:
        b, ctx, page = await new_phone(p, port, log, problems)

        # ---- A. boot and layout ----
        check("A1 title is Explore", await page.title() == "ECHO · Explore")
        tabs = await page.eval_on_selector_all(".tab", "els => els.map(e => e.textContent.trim())")
        check("A2 four tabs", tabs == ["Explore", "Pulse", "Saved", "Ask"], tabs)
        check("A3 explore tab active", await page.get_attribute(".tab[data-nav=explore]", "aria-current") == "page")
        check("A4 no horizontal overflow", await page.evaluate("document.documentElement.scrollWidth <= innerWidth && document.body.scrollWidth <= innerWidth"))
        check("A5 starts at peek", await page.evaluate("window.__echo.views.explore.snap()") == "peek")
        stage = await rect(page, ".stage")
        head = await rect(page, ".bsheet-head")
        mapr = await rect(page, ".map-area")
        check("A6 map fills above the peek sheet", abs(mapr["h"] - (stage["h"] - head["h"])) < 2, (mapr, head, stage))
        check("A7 body inert at peek", await page.evaluate("document.querySelector('.bsheet-body').inert === true"))
        check("A8 chip shows title + legend", "Glacier flash flood" in await page.inner_text(".title-chip") and "no overlay" in await page.inner_text(".title-chip"))
        small = await page.evaluate("""() => [...document.querySelectorAll('.explore button:not([hidden]), .tabbar button')].filter(b => b.offsetParent && !b.closest('.bsheet-body') && !b.classList.contains('bsheet-grab')).map(b => { const r = b.getBoundingClientRect(); return [b.className || b.getAttribute('aria-label'), Math.min(r.width, r.height)]; }).filter(([n, m]) => m < 40)""")
        check("A9 all primary buttons >= 40px", not small, small)

        # ---- B. sheet snaps ----
        await page.click(".expand-btn"); await page.wait_for_timeout(500)
        check("B1 expand button -> half", await page.evaluate("window.__echo.views.explore.snap()") == "half")
        sheet = await rect(page, ".bsheet")
        stage = await rect(page, ".stage")
        check("B2 half is about half the screen", abs((stage["h"] - sheet["y"]) - round(stage["h"] * 0.52)) < 3, (sheet, stage))
        mapr = await rect(page, ".map-area")
        check("B3 map shrinks to visible area at half", abs(mapr["h"] - sheet["y"]) < 3, (mapr, sheet))
        check("B4 body no longer inert", await page.evaluate("document.querySelector('.bsheet-body').inert === false"))
        check("B5 report visible", "ESA reports" in await page.inner_text(".bsheet-panel"))
        grab = await rect(page, ".bsheet-grab")
        await drag(page, grab["cx"], grab["cy"], grab["cx"], 120)   # slow drag up
        await page.wait_for_timeout(500)
        check("B6 drag up -> full", await page.evaluate("window.__echo.views.explore.snap()") == "full")
        sheet = await rect(page, ".bsheet")
        check("B7 full sheet reaches the top gap", sheet["y"] < 20, sheet)
        grab = await rect(page, ".bsheet-grab")
        await drag(page, grab["cx"], grab["cy"], grab["cx"], grab["cy"] + 160, steps=10, delay=40)  # a medium drag down
        await page.wait_for_timeout(500)
        check("B8 drag down -> half", await page.evaluate("window.__echo.views.explore.snap()") == "half", await page.evaluate("window.__echo.views.explore.snap()"))
        grab = await rect(page, ".bsheet-grab")
        await drag(page, grab["cx"], grab["cy"], grab["cx"], grab["cy"] + 500, steps=6, delay=8)  # flick down
        await page.wait_for_timeout(500)
        check("B9 flick down -> peek", await page.evaluate("window.__echo.views.explore.snap()") == "peek")
        grab = await rect(page, ".bsheet-grab")
        await page.mouse.click(grab["cx"], grab["cy"]); await page.wait_for_timeout(450)
        s1 = await page.evaluate("window.__echo.views.explore.snap()")
        await page.mouse.click(grab["cx"], await page.evaluate("document.querySelector('.bsheet-grab').getBoundingClientRect().top + 12")); await page.wait_for_timeout(450)
        s2 = await page.evaluate("window.__echo.views.explore.snap()")
        check("B10 grabber tap cycles peek->half->full", (s1, s2) == ("half", "full"), (s1, s2))
        # a drag that starts on a timeline stop must not also select it
        await page.evaluate("window.__echo.views.explore.setSnap('peek')"); await page.wait_for_timeout(450)
        before_date = await page.inner_text(".dock-text strong")
        stop = await rect(page, ".stop:nth-child(1)")
        await drag(page, stop["cx"], stop["cy"], stop["cx"], stop["cy"] - 200, steps=10, delay=40); await page.wait_for_timeout(450)
        check("B11 drag from a stop moves the sheet, does not select the date", await page.evaluate("window.__echo.views.explore.snap()") != "peek" and await page.inner_text(".dock-text strong") == before_date)
        await page.evaluate("window.__echo.views.explore.setSnap('peek')"); await page.wait_for_timeout(450)
        # keyboard
        await page.focus(".bsheet-grab"); await page.keyboard.press("ArrowUp"); await page.wait_for_timeout(400)
        check("B12 ArrowUp on grabber -> half", await page.evaluate("window.__echo.views.explore.snap()") == "half")
        await page.keyboard.press("ArrowDown"); await page.wait_for_timeout(400)
        check("B13 ArrowDown -> peek", await page.evaluate("window.__echo.views.explore.snap()") == "peek")
        # back button
        await page.evaluate("window.__echo.views.explore.setSnap('full')"); await page.wait_for_timeout(400)
        r1 = await page.evaluate("window.__echo.app.back()"); await page.wait_for_timeout(300)
        r2 = await page.evaluate("window.__echo.app.back()"); await page.wait_for_timeout(300)
        r3 = await page.evaluate("window.__echo.app.back()")
        check("B14 back: full->half->peek->exit", (r1, r2, r3) == (True, True, False) and await page.evaluate("window.__echo.views.explore.snap()") == "peek", (r1, r2, r3))

        # ---- C. timeline ----
        log.clear()
        await page.click(".stop:nth-child(1)"); await page.wait_for_timeout(600)
        check("C1 first stop selected", "12 August 2026" in await page.inner_text(".dock-text strong"))
        check("C2 GIBS asked for the selected date", any(e[0] == "gibs" and e[1] == "2026-08-12" for e in log), [e[1] for e in log if e[0] == "gibs"][:5])
        check("C3 stop marked current", await page.get_attribute(".stop:nth-child(1)", "aria-current") == "step")
        await page.click(".play-btn"); await page.wait_for_timeout(2900)
        d = await page.inner_text(".dock-text strong")
        check("C4 play advances the date", "12 August" not in d, d)
        check("C5 pause label while playing", await page.get_attribute(".play-btn", "aria-label") == "Pause")
        await page.click(".play-btn"); await page.wait_for_timeout(200)
        check("C6 paused", await page.get_attribute(".play-btn", "aria-label") == "Play through the dates")
        await page.click(".stop:nth-child(3)"); await page.wait_for_timeout(300)

        # ---- D. compare ----
        await page.click(".fab[aria-label='Compare before and after']"); await page.wait_for_timeout(1000)
        check("D1 compare layer visible", await page.is_visible(".compare-layer"))
        labels = await page.inner_text(".compare-labels")
        check("D2 before/after labels", "Before" in labels and "After" in labels, labels)
        mapr = await rect(page, ".map-area")
        img = await shot_pixels(page)
        y = int(mapr["h"] * 0.6)
        check("D3 left of divider shows BEFORE colour (red)", near(img.getpixel((60, y)), (200, 40, 40)), img.getpixel((60, y)))
        check("D4 right of divider shows AFTER colour (blue)", near(img.getpixel((330, y)), (40, 90, 220)), img.getpixel((330, y)))
        hr = await rect(page, ".compare-handle .grip")
        check("D5 grip is a 44px+ touch target", hr["w"] >= 44 and hr["h"] >= 44, hr)
        await drag(page, hr["cx"], hr["cy"], 300, hr["cy"], steps=10, delay=20); await page.wait_for_timeout(500)
        img = await shot_pixels(page)
        check("D6 dragging moves the divider (x=250 now BEFORE)", near(img.getpixel((250, y)), (200, 40, 40)), img.getpixel((250, y)))
        check("D7 right of new divider still AFTER", near(img.getpixel((360, y)), (40, 90, 220)), img.getpixel((360, y)))
        v = int(await page.get_attribute(".compare-handle", "aria-valuenow"))
        check("D8 aria-valuenow follows the drag", 70 <= v <= 82, v)
        await page.focus(".compare-handle"); await page.keyboard.press("ArrowLeft"); await page.keyboard.press("ArrowLeft")
        check("D9 keyboard moves divider", int(await page.get_attribute(".compare-handle", "aria-valuenow")) == v - 4)
        # panning the map must still work outside the handle and keep the clip aligned
        await drag(page, 60, y, 120, y - 40, steps=6, delay=15); await page.wait_for_timeout(400)
        img = await shot_pixels(page)
        check("D10 panning keeps before/after split", near(img.getpixel((60, y)), (200, 40, 40)) and near(img.getpixel((370, y)), (40, 90, 220)))
        await page.click(".stop:nth-child(1)"); await page.wait_for_timeout(400)
        check("D11 hint when first==selected", await page.is_visible(".map-note:not(.warn)"))
        await page.click(".fab[aria-label='Compare before and after']"); await page.wait_for_timeout(500)
        check("D12 compare off hides divider, labels, hint", not await page.is_visible(".compare-layer") and not await page.is_visible(".compare-labels") and not await page.is_visible(".map-note:not(.warn)"))
        await page.click(".fab[aria-label='Compare before and after']"); await page.wait_for_timeout(500)
        check("D13 turning compare on from the first date jumps to the last", "03 September 2026" in await page.inner_text(".dock-text strong") or "September" in await page.inner_text(".dock-text strong"), await page.inner_text(".dock-text strong"))
        await page.click(".fab[aria-label='Compare before and after']"); await page.wait_for_timeout(300)

        # ---- E. notes and pins ----
        await page.evaluate("window.__echo.views.explore.setSnap('half')"); await page.wait_for_timeout(500)
        await page.click("#m-tab-notes"); await page.wait_for_timeout(200)
        await page.click("text=Add note"); await page.wait_for_timeout(300)
        check("E1 empty note is rejected with a message", "Write something" in await page.inner_text(".toast"))
        check("E1b a rejected note refocuses the field (sheet goes full)", await page.evaluate("window.__echo.views.explore.snap()") == "full")
        await page.evaluate("document.activeElement.blur(); window.__echo.views.explore.setSnap('half')"); await page.wait_for_timeout(500)
        await page.click("button:has-text('Pin to map')"); await page.wait_for_timeout(600)
        check("E2 pin mode: banner visible, top bar + fabs hidden", await page.is_visible(".mode-bar") and not await page.is_visible(".top-bar") and not await page.is_visible(".fabs"))
        check("E3 pin mode collapses sheet to peek", await page.evaluate("window.__echo.views.explore.snap()") == "peek")
        await page.click(".mode-bar .btn"); await page.wait_for_timeout(600)
        check("E4 cancel restores half + controls", await page.evaluate("window.__echo.views.explore.snap()") == "half" and await page.is_visible(".fabs") and not await page.is_visible(".mode-bar"))
        await page.click("button:has-text('Pin to map')"); await page.wait_for_timeout(500)
        r = await page.evaluate("window.__echo.app.back()"); await page.wait_for_timeout(500)
        check("E5 back button cancels pin mode", r is True and not await page.is_visible(".mode-bar"))
        await page.click("button:has-text('Pin to map')"); await page.wait_for_timeout(600)
        await page.mouse.click(200, 300); await page.wait_for_timeout(700)
        check("E6 tap places a draft pin", await page.locator(".echo-note-draft").count() == 1)
        check("E7 sheet returns to half and shows the location", await page.evaluate("window.__echo.views.explore.snap()") == "half" and await page.is_visible(".note-location"))
        await page.fill(".composer textarea", "Debris field north of the bridge"); await page.wait_for_timeout(500)
        check("E8 focusing the note field lifts the sheet to full", await page.evaluate("window.__echo.views.explore.snap()") == "full")
        await page.click("button:has-text('Add note')"); await page.wait_for_timeout(500)
        inv = await page.evaluate("window.__echo.app.store.active().id")
        notes = await page.evaluate("(id) => window.__echo.app.store.notes(id)", inv)
        check("E9 note stored with coordinates and date index", len(notes) == 1 and notes[0].get("lat") is not None and notes[0].get("dateIndex") is not None, notes)
        check("E10 draft pin replaced by a real note pin", await page.locator(".echo-note-draft").count() == 0 and await page.locator(".echo-note-pin").count() == 1)
        check("E11 note card + count in tab", await page.locator(".note-list .note").count() == 1 and "Notes · 1" in await page.inner_text("#m-tab-notes"))
        await page.click(".note button[aria-label='Show on map']"); await page.wait_for_timeout(1700)
        check("E12 show-on-map collapses sheet and opens popup", await page.evaluate("window.__echo.views.explore.snap()") == "peek" and await page.is_visible(".echo-popup"))
        await page.evaluate("window.__echo.views.explore.setSnap('half')"); await page.wait_for_timeout(500)
        # persistence
        await page.wait_for_timeout(400)
        await page.reload(); await page.wait_for_selector(".bsheet"); await page.wait_for_timeout(800)
        notes = await page.evaluate("(id) => window.__echo.app.store.notes(id)", inv)
        check("E13 note survives reload", len(notes) == 1 and notes[0]["text"].startswith("Debris"))
        await page.evaluate("window.__echo.views.explore.setSnap('half')"); await page.wait_for_timeout(500)
        await page.click("#m-tab-notes"); await page.wait_for_timeout(200)
        await page.click(".note button[aria-label='Delete note']"); await page.wait_for_timeout(500)
        check("E14 delete asks first", "Delete this note?" in await page.inner_text(".sheet-panel"))
        await page.click(".sheet-foot .btn-danger"); await page.wait_for_timeout(500)
        check("E15 note deleted", await page.locator(".note-list .note").count() == 0)

        # ---- G. layers ----
        await page.evaluate("window.__echo.views.explore.setSnap('peek')"); await page.wait_for_timeout(500)
        await page.click(".fab-lg[aria-label='Map layers']"); await page.wait_for_timeout(500)
        await page.click("input[data-layer=notes] ~ .switch"); await page.wait_for_timeout(100)
        check("G1 notes layer off", await page.evaluate("window.__echo.views.explore.snap && true") and not await page.evaluate("document.querySelector('input[data-layer=notes]').checked"))
        log.clear()
        await page.click("input[data-layer=fires] ~ .switch"); await page.wait_for_timeout(900)
        check("G2 fires layer requests GIBS thermal tiles", any(e[0] == "gibs" and e[2].startswith("MODIS_Terra_Thermal") for e in log), [e[2] for e in log if e[0] == "gibs"][:4])
        await page.click("input[data-layer=labels] ~ .switch"); await page.wait_for_timeout(200)
        check("G3 place names setting persisted", await page.evaluate("window.__echo.app.store.settings().showLabels") is False)
        await page.click(".chip:has-text('MODIS Aqua')"); await page.wait_for_timeout(700)
        check("G4 imagery source changed", await page.evaluate("window.__echo.app.store.settings().imagery") == "aqua", await page.evaluate("window.__echo.app.store.settings().imagery"))
        check("G5 gibs now asks for Aqua", any(e[0] == "gibs" and "Aqua" in e[2] for e in log), [e[2] for e in log if e[0] == "gibs"][-3:])
        await page.click(".sheet-foot .btn-primary"); await page.wait_for_timeout(400)
        check("G6 sheet closes", await page.locator(".sheet-modal").count() == 0)

        # ---- zero errors ----
        ok = summary(problems)
        await b.close()
        sys.exit(0 if ok else 1)
asyncio.run(main())
